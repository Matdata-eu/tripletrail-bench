#!/usr/bin/env python3
"""Turns results/oltp/results.jsonl (lines written by `oltp run -out`) into results/oltp/report.md."""
import json, os, sys

V2 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(V2, "results", "oltp", "results.jsonl")
rows = [json.loads(l) for l in open(src) if l.strip()]
rows = [r for r in rows if r["scenario"] != "warm"]
cfgs = []
for r in rows:
    k = (r["engine"], r["scenario"])
    if k not in cfgs:
        cfgs.append(k)
d = {(r["engine"], r["scenario"], r["workload"], r["clients"]): r for r in rows}
workloads = []
for r in rows:
    if r["workload"] not in workloads:
        workloads.append(r["workload"])
out = ["# OLTP results", "",
       "Requests per second, and p50 / p99 latency in ms at the client, by number of concurrent "
       "clients. Generated by `suites/oltp/report.py` from `results.jsonl`; see "
       "`suites/oltp/README.md` for the workloads and the machine.", ""]
for w in workloads:
    out += [f"## {w}", "", "| clients | " + " | ".join(f"{e} ({s})" for e, s in cfgs) + " |",
            "|---" * (len(cfgs) + 1) + "|"]
    clients = sorted({r["clients"] for r in rows if r["workload"] == w})
    for c in clients:
        cells = []
        for e, s in cfgs:
            r = d.get((e, s, w, c))
            if not r:
                cells.append("")
                continue
            a = r["all"]
            err = f", {a['errors']} errors" if a["errors"] else ""
            cells.append(f"{r['ops_per_s']:,.0f} ({a['p50_ms']:.2f} / {a['p99_ms']:.1f}{err})")
        out.append(f"| {c} | " + " | ".join(cells) + " |")
    out.append("")
dst = os.path.join(os.path.dirname(src), "report.md")
open(dst, "w").write("\n".join(out))
print(dst)
